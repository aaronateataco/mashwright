"""Generate the mod's data code from the design sheets.

Every sheet row becomes one GDScript constant dictionary (the GDScript equivalent of a struct),
built only from that row's columns. The sheets are the source of truth: edit them, then rerun.

usage: python tools/gen.py
"""
import json
import os

from sheets_lib import MOD_DIR, SHEET_NAMES, load_all

# Sheets the running mod needs (package/tests/hooks are build- and review-time only).
RUNTIME_SHEETS = [
    "hue_assets", "colours", "regions", "character", "layers", "effects", "items", "weapons",
    "synergies", "tuning", "options", "input", "sounds", "enemy_rules", "hazards", "letters", "strings",
]


def gd_literal(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        return "[" + ", ".join(gd_literal(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{json.dumps(k)}: {gd_literal(v)}" for k, v in value.items()) + "}"
    raise TypeError(f"cannot express {type(value)} in GDScript")


def row_struct(columns: list, row: dict) -> str:
    # Columns in sheet order so every row reads the same way.
    return "{" + ", ".join(f"{json.dumps(c)}: {gd_literal(row[c])}" for c in columns) + "}"


def main() -> None:
    sheets = load_all()
    out = [
        "# GENERATED by tools/gen.py from sheets/*.json. Edit the sheets, then regenerate.",
        "extends Reference",
        "",
    ]
    for name in RUNTIME_SHEETS:
        sheet = sheets[name]
        const = name.upper()
        out.append(f"# {sheet['about']}")
        out.append(f"const {const} = {{")
        for row in sheet["rows"]:
            out.append(f"\t{json.dumps(row['id'])}: {row_struct(sheet['columns'], row)},")
        out.append("}")
        out.append(f"const {const}_ORDER = {gd_literal([r['id'] for r in sheet['rows']])}")
        out.append("")
    path = os.path.join(MOD_DIR, "generated", "sheets.gd")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", path, sum(len(sheets[n]["rows"]) for n in RUNTIME_SHEETS), "rows")
    unused = [n for n in SHEET_NAMES if n not in RUNTIME_SHEETS]
    print("build-time sheets (not in mod):", ", ".join(unused))


if __name__ == "__main__":
    main()
